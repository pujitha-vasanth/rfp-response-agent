"""
Turns the final state into the two things a bid team needs:

1. A compliance matrix (Excel) for the internal team, including a gap list.
2. A draft response document (Word) to send to the buyer after human review.
"""

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from docx import Document
from docx.shared import Pt, RGBColor

from rfp_agent import config, knowledge

STATUS_LABELS = {"Full": "Fully compliant", "Partial": "Partially compliant", "None": "Not compliant"}
STATUS_COLOURS = {"Full": "D9F2E3", "Partial": "FFF1CC", "None": "F9D6D5"}


def pretty_name(file_stem: str) -> str:
    """harbourview_logistics_rfp -> Harbourview Logistics RFP"""
    words = file_stem.replace("-", " ").replace("_", " ").split()
    return " ".join(w.upper() if w.lower() in ("rfp", "itt", "rfq") else w.capitalize() for w in words)


def build_rows(state: dict) -> list[dict]:
    """One flat row per requirement, combining what all four agents produced."""
    titles = {c["id"]: c["title"] for c in knowledge.load_library()}
    rows = []
    for req in state["requirements"]:
        match = state["matches"][req["id"]]
        answer = state.get("answers", {}).get(req["id"])

        if match["status"] == "None":
            human_action = "Not met: decide whether to bid, partner or offer an alternative."
        elif answer and not answer["passed"]:
            human_action = f"Reviewer did not pass this after {answer['drafts']} drafts: edit the answer."
        elif match["status"] == "Partial":
            human_action = "Partly met: confirm the alternative and any extra cost."
        else:
            human_action = ""

        rows.append({
            "id": req["id"],
            "section": req["section"],
            "requirement": req["text"],
            "priority": req["priority"],
            "status": match["status"],
            "evidence": ", ".join(f"{i} {titles.get(i, '')}" for i in match["evidence_ids"]),
            "reason": match["reason"],
            "answer": answer["text"] if answer else "",
            "review_score": answer["score"] if answer else None,
            "drafts": answer["drafts"] if answer else 0,
            "human_action": human_action,
        })
    return rows


def export_excel(rows: list[dict], destination) -> None:
    """destination can be a file path or an in-memory buffer."""
    wb = Workbook()

    ws = wb.active
    ws.title = "Compliance Matrix"
    headers = ["Req ID", "Section", "Requirement", "Priority", "Compliance", "Evidence",
               "Draft answer", "Review score", "Drafts", "Action for human"]
    keys = ["id", "section", "requirement", "priority", "status", "evidence",
            "answer", "review_score", "drafts", "human_action"]
    widths = [8, 26, 50, 12, 20, 32, 70, 12, 8, 40]
    _write_sheet(ws, headers, widths, [[r[k] for k in keys] for r in rows], rows)

    gaps = [r for r in rows if r["human_action"]]
    ws_gaps = wb.create_sheet("Needs Human Decision")
    _write_sheet(
        ws_gaps,
        ["Req ID", "Requirement", "Priority", "Compliance", "Why", "Action for human"],
        [8, 60, 12, 20, 50, 45],
        [[r["id"], r["requirement"], r["priority"], r["status"], r["reason"], r["human_action"]] for r in gaps],
        gaps,
    )
    wb.save(destination)


def _write_sheet(ws, headers, widths, values, rows):
    header_fill = PatternFill("solid", fgColor="1F3A5F")
    for col, (header, width) in enumerate(zip(headers, widths), start=1):
        cell = ws.cell(row=1, column=col, value=header)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = header_fill
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        ws.column_dimensions[cell.column_letter].width = width

    status_col = headers.index("Compliance") + 1
    for row_number, (row_values, row) in enumerate(zip(values, rows), start=2):
        for col, value in enumerate(row_values, start=1):
            cell = ws.cell(row=row_number, column=col, value=value)
            cell.alignment = Alignment(vertical="top", wrap_text=True)
        status_cell = ws.cell(row=row_number, column=status_col)
        status_cell.value = STATUS_LABELS[row["status"]]
        status_cell.fill = PatternFill("solid", fgColor=STATUS_COLOURS[row["status"]])

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions


def export_word(rows: list[dict], rfp_title: str, destination) -> None:
    """Draft proposal response, grouped by RFP section. Gaps are marked for the bid team."""
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    doc.add_heading(f"{config.COMPANY_NAME}: Response to {rfp_title}", level=0)
    note = doc.add_paragraph("DRAFT for internal review. Generated by the RFP response agent team. "
                             "Every answer must be checked by the bid team before submission.")
    note.runs[0].italic = True

    current_section = None
    for row in rows:
        if row["section"] != current_section:
            current_section = row["section"]
            doc.add_heading(current_section, level=1)

        p = doc.add_paragraph()
        p.add_run(f"{row['id']} ({row['priority']}): ").bold = True
        p.add_run(row["requirement"])

        status_line = doc.add_paragraph()
        status_run = status_line.add_run(f"Compliance: {STATUS_LABELS[row['status']]}")
        status_run.bold = True

        if row["answer"]:
            doc.add_paragraph(row["answer"])
        if row["human_action"]:
            flag = doc.add_paragraph().add_run(f"[Bid team: {row['human_action']}]")
            flag.italic = True
            flag.font.color.rgb = RGBColor(0xB0, 0x3A, 0x2E)

    doc.save(destination)
